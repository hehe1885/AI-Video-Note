const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const frontend=path.join(__dirname,'..','frontend');
const input={checked:false,disabled:true,dataset:{}};
const nodes={autostartEnabled:input,autostartStatus:{textContent:''},viewLogsBtn:{disabled:false},viewLogsStatus:{textContent:''}};
const calls=[];
const sandbox={console,URL,setTimeout,clearTimeout,document:{getElementById:id=>nodes[id],addEventListener(){}},window:{addEventListener(){}},record:(url,options,timeout)=>calls.push([url,options,timeout])};
vm.createContext(sandbox);
vm.runInContext(['api.js','tasks.js','settings.js','gpu-runtime.js','script.js','note-view.js'].map(name=>fs.readFileSync(path.join(frontend,name),'utf8')).join('\n'),sandbox);
const run=code=>vm.runInContext(code,sandbox);
sandbox.response={supported:true,enabled:true};
run('fetchWithTimeout=async (url,options,timeout)=>{record(url,options,timeout);return response};readResponse=async response=>response');
(async()=>{
 await run('loadAutostartSetting()');
 assert.equal(input.checked,true); assert.equal(input.disabled,false);
 assert.equal(calls.length,1); assert.equal(calls[0][1].method,undefined);
 assert.equal(calls[0][2],10000);
 input.checked=false; sandbox.response={supported:true,enabled:false};
 await run('saveAutostartSetting()');
 assert.equal(calls.at(-1)[1].method,'PUT');
 assert.deepEqual(JSON.parse(calls.at(-1)[1].body),{enabled:false});
 assert.equal(input.dataset.savedEnabled,'false');
 run('fetchWithTimeout=async()=>{throw Error("denied")};');
 input.checked=true;
 await run('saveAutostartSetting()');
 assert.equal(input.checked,false); assert.equal(input.disabled,false);
 assert.match(nodes.autostartStatus.textContent,/失败/);
 input.disabled=true;
 await run('loadAutostartSetting()');
 assert.equal(input.disabled,true);
 run('fetchWithTimeout=async (url,options,timeout)=>{record(url,options,timeout);return response};');
 sandbox.response={supported:false,enabled:false};
 await run('loadAutostartSetting()');
 assert.equal(input.disabled,true); assert.match(nodes.autostartStatus.textContent,/暂不支持/);
 sandbox.response={opened:true};
 await run('openAppLog()');
 assert.match(calls.at(-1)[0],/\/log\/open$/); assert.equal(calls.at(-1)[1].method,'POST');
 assert.equal(nodes.viewLogsBtn.disabled,false);
 run('fetchWithTimeout=async()=>{throw Error("missing log")};');
 await run('openAppLog()');
 assert.equal(nodes.viewLogsBtn.disabled,false); assert.match(nodes.viewLogsStatus.textContent,/无法打开/);
 console.log('Software startup read, toggle, rollback, platform gate and log opening checks passed');
})().catch(error=>{console.error(error);process.exitCode=1});
