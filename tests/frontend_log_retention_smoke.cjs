const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const frontend=path.join(__dirname,'..','frontend');
const input={value:'5',disabled:true,dataset:{},checkValidity:()=>true,reportValidity(){}};
const status={textContent:''};
const nodes={logRetentionDays:input,logRetentionStatus:status};
const calls=[];
const sandbox={console,URL,setTimeout,clearTimeout,document:{getElementById:id=>nodes[id],addEventListener(){}},window:{addEventListener(){}},record:(url,options,timeout)=>calls.push([url,options,timeout])};
vm.createContext(sandbox);
vm.runInContext(['api.js','tasks.js','settings.js','gpu-runtime.js','script.js','note-view.js'].map(name=>fs.readFileSync(path.join(frontend,name),'utf8')).join('\n'),sandbox);
const run=code=>vm.runInContext(code,sandbox);
run('fetchWithTimeout=async (url,options,timeout)=>{record(url,options,timeout);return {days:7}};readResponse=async response=>response');
(async()=>{
 await run('loadLogRetention()');
 assert.equal(input.value,7); assert.equal(input.disabled,false);
 assert.equal(calls.at(-1)[2],10000);
 input.value='10';
 await run('saveLogRetention()');
 assert.equal(calls.at(-1)[1].method,'PUT');
 assert.equal(calls.at(-1)[2],10000);
 assert.deepEqual(JSON.parse(calls.at(-1)[1].body),{days:10});
 assert.equal(status.textContent,'已保存');
 input.value='20';
 run('fetchWithTimeout=async()=>{throw Error("network")};');
 await run('saveLogRetention()');
 assert.equal(input.value,'7'); assert.equal(input.disabled,false);
 assert.match(status.textContent,/失败/);
 input.checkValidity=()=>false;
 const before=calls.length;
 await run('saveLogRetention()');
 assert.equal(calls.length,before);
 console.log('Log retention load, save, validation and failed-save rollback passed');
})().catch(error=>{console.error(error);process.exitCode=1});
